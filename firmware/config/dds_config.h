/**
 * @file dds_config.h
 * @brief Параметры изделия DDS 48–52 МГц (ревизия платы F).
 *
 * Здесь собраны все числа, которые относятся к изделию, а не к драйверам.
 * Менять диапазон, шаг, такт DDS или амплитуду нужно только здесь.
 * Источники: docs/design_notes.md (разд. 5), docs/REVISION_F.md,
 * ТО 1508ПЛ8Т (14.10.2020), ТО 1887ВЕ7Т КФДЛ.431295.044ТО.
 */
#ifndef DDS_CONFIG_H
#define DDS_CONFIG_H

/* ---------------------------------------------------------------------------
 * Микроконтроллер D2 1887ВЕ7Т (аналог ATmega128)
 * ------------------------------------------------------------------------- */

/** Тактовая частота ядра: внутренний RC 8 МГц (CKSEL=0100). Задаётся из CMake. */
#ifndef F_CPU
#error "F_CPU must be defined by the build system (CMake: DDS_F_CPU)"
#endif

/* ---------------------------------------------------------------------------
 * Задание частоты: f = DDS_F_BASE_HZ + DDS_F_STEP_HZ * N
 * N — 12-разрядный код DIP-переключателей S2 (биты 0..7) и S3 (биты 8..11).
 * ------------------------------------------------------------------------- */
#define DDS_F_BASE_HZ      48000000UL  /**< частота при N = 0 */
#define DDS_F_STEP_HZ      1000UL      /**< шаг */
#define DDS_N_MAX          4000U       /**< N = 0…4000; 4001…4095 отвергаются */

/* ---------------------------------------------------------------------------
 * Синтезатор D1 1508ПЛ8Т
 * ------------------------------------------------------------------------- */

/** Тактовая частота ЦАП (вход XW1 при CSEL=1 или G1 при CSEL=0), Гц. */
#define DDS_FCLK_HZ        480000000UL

/**
 * Делитель тактовой частоты CTR.cmx (ТО, табл. 5.3). Действует только при
 * CSEL=0 (вход CLKP/CLKM, генератор G1): 0 → 1:1, 1 → 1:2, 3 → 1:4.
 * При CSEL=1 (вход CLKDP/CLKDM, XW1) деление всегда 1. DDS_FCLK_HZ —
 * частота уже после делителя.
 */
#define DDS_CLK_CMX        0U

/**
 * Амплитуда, поле mul регистра CHx_Muly (ТО, табл. 5.13): A = mul / 4096,
 * mul — 13-разрядное число в дополнительном коде, 0…4095.
 * Уровень −10 дБм на выходе калибруется на макете; 4095 — полная шкала.
 */
#define DDS_AMPLITUDE_MUL  4095U

/**
 * Время переключения параметров (гауссов фильтр), поле tsw регистра CH1_TSW
 * (ТО, табл. 5.8). 0 — мгновенное переключение частоты.
 */
#define DDS_TSW            0U

/** Рандомизация фазы канала 1 (ROUTE.pdith1, ТО табл. 5.7): 0 — выкл, 1 — вкл. */
#define DDS_PHASE_DITHER   0U

/* ---------------------------------------------------------------------------
 * Тайминги запуска и обслуживания
 * ------------------------------------------------------------------------- */

/** Пауза после старта МК до снятия сброса DDS. Шина +1,8 В не контролируется
 *  (design_notes, разд. 4, п. 7): ждать не менее 10 мс. */
#define DDS_POWER_SETTLE_MS     20U
/** Подтверждение высокого PGOOD перед включением; низкий отключает без фильтра. */
#define DDS_PGOOD_STABLE_MS     10U
/** Длительность импульса RSTn (ТО: не менее 10 тактов CLK). */
#define DDS_RESET_PULSE_MS      2U
/** Пауза после снятия RSTn до первой SPI-команды. */
#define DDS_RESET_RECOVERY_MS   2U
/** Повтор инициализации после ошибки (нет такта, нет связи по SPI). */
#define DDS_RETRY_PERIOD_MS     500U
/** Период проверки, что DDS не сбросился (чтение CTR). 0 — не проверять. */
#define DDS_HEALTH_PERIOD_MS    1000U

/** Подавление дребезга кнопки «Применить» (S4), мс. */
#define APPLY_DEBOUNCE_MS       20U
/** Интервал между двумя чтениями DIP; значение принимается, если они совпали. */
#define DIP_SETTLE_MS           10U
/** Сколько раз пытаться получить два совпавших чтения DIP. */
#define DIP_READ_ATTEMPTS       5U

/** Сторожевой таймер: период (константа avr-libc WDTO_*). Включается опцией
 *  CMake DDS_WDT (Release — вкл., Debug — выкл., чтобы не мешал остановкам JTAG). */
#ifndef DDS_WDT
#define DDS_WDT 1
#endif
#define DDS_WDT_TIMEOUT         WDTO_1S

/* ---------------------------------------------------------------------------
 * SPI к 1508ПЛ8Т
 * ------------------------------------------------------------------------- */

/**
 * Делитель SPI (ATmega128: 4, 16, 64, 128; с SPI2X — 2, 8, 32, 64).
 * 128 → 62,5 кГц при 8 МГц. design_notes: SPI не быстрее 100 кГц из-за
 * согласования уровней через D3/D4 и резисторы 1 кОм. Сам 1508ПЛ8Т допускает
 * период SCLK от max(20 нс, 10·tCLK).
 */
#define DDS_SPI_PRESCALER       128U

/* ---------------------------------------------------------------------------
 * Отладочный вывод: USART0 TX = PE1 = площадка X1.1 (ISP_PDO), 8N1
 * ------------------------------------------------------------------------- */
#ifndef DDS_LOG
#define DDS_LOG 0                      /**< задаётся из CMake: Debug — 1, Release — 0 */
#endif
#define DDS_LOG_BAUD            38400UL

/* ---------------------------------------------------------------------------
 * EEPROM: калибровка RC 8 МГц (байт OSCCAL записывается программатором,
 * см. README, раздел «Калибровка RC»). Рядом хранится его дополнение.
 * ------------------------------------------------------------------------- */
#define EE_ADDR_OSCCAL          0x000U
#define EE_ADDR_OSCCAL_INV      0x001U

/* ---------------------------------------------------------------------------
 * Проверки на этапе компиляции
 * ------------------------------------------------------------------------- */
_Static_assert(DDS_FCLK_HZ < 2147483648UL, "freq_hz_to_ftw() needs Fclk < 2^31");
_Static_assert((DDS_F_BASE_HZ + DDS_F_STEP_HZ * DDS_N_MAX) < (DDS_FCLK_HZ / 5UL * 2UL),
               "Output frequency must stay well below Nyquist (0.4*Fclk)");
_Static_assert(DDS_N_MAX <= 4095U, "N is a 12-bit DIP code");
_Static_assert(DDS_AMPLITUDE_MUL <= 4095U, "mul is a 13-bit signed value, max 4095");
_Static_assert(DDS_TSW <= 7U, "tsw is a 3-bit field");
_Static_assert(DDS_CLK_CMX <= 31U, "cmx is a 5-bit field");

#endif /* DDS_CONFIG_H */
